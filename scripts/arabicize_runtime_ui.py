allowed = {'.vue', '.ts', '.tsx', '.js', '.html'}
changed = []
for base in TARGETS:
    paths = [base] if base.is_file() else [p for p in base.rglob('*') if p.is_file() and p.suffix.lower() in allowed] if base.exists() else []
    for path in paths:
        text = path.read_text(encoding='utf-8')
        original = text
        for source, target in replacements:
            text = text.replace(source, target)
        if text != original:
            path.write_text(text, encoding='utf-8')
            changed.append(str(path.relative_to(ROOT)))

print(f'Arabicized {len(changed)} UI files')
for item in changed:
    print(item)
