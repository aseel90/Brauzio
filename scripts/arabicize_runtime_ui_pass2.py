replacements = sorted(R.items(), key=lambda item: len(item[0]), reverse=True)
allowed = {'.vue', '.ts', '.tsx', '.js', '.html'}
changed = []
for base in TARGETS:
    if base.is_file():
        paths = [base]
    elif base.exists():
        paths = [p for p in base.rglob('*') if p.is_file() and p.suffix.lower() in allowed]
    else:
        paths = []
    for path in paths:
        text = path.read_text(encoding='utf-8')
        original = text
        for source, target in replacements:
            text = text.replace(source, target)
        if text != original:
            path.write_text(text, encoding='utf-8')
            changed.append(str(path.relative_to(ROOT)))

print(f'Arabic UI pass 2 changed {len(changed)} files')
for path in changed:
    print(path)
