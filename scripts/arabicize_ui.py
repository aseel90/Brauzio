PHRASES.update(LOADING)

changed_files = 0
for base in ROOTS:
    if not base.exists():
        continue
    for path in base.rglob('*'):
        if not path.is_file() or path.suffix.lower() not in EXTS:
            continue
        original = path.read_text(encoding='utf-8')
        text = original
        for source, target in sorted(PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
            text = text.replace(source, target)
        if text != original:
            path.write_text(text, encoding='utf-8')
            changed_files += 1

print(f'Arabicized UI files: {changed_files}')

# Report remaining CJK after this pass; do not delete unknown runtime strings.
remaining = []
for base in ROOTS:
    if not base.exists():
        continue
    for path in base.rglob('*'):
        if not path.is_file() or path.suffix.lower() not in EXTS:
            continue
        for n, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
            if CJK.search(line):
                remaining.append((str(path.relative_to(ROOT)), n, line.strip()[:160]))

print(f'Remaining UI CJK lines after translation pass: {len(remaining)}')
